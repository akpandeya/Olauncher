package app.olauncher.data.store

/**
 * Context-free packing for the stored API key file (no Android APIs, unit-tested):
 * `version (1 byte) | iv (12 bytes) | ciphertext`. [unpack] rejects truncated or
 * unsupported input instead of producing a partial result — [KeyVault.read] deletes
 * the file and returns null in that case, so a stale or cut-off file can never
 * yield a key.
 */
object KeyVaultCodec {

    /** Bump when the file layout changes; files with another version are unreadable. */
    const val VERSION: Int = 1

    private const val VERSION_SIZE = 1

    /** AES-GCM standard 96-bit IV size, as generated by the platform cipher. */
    private const val IV_SIZE = 12

    /** The GCM authentication tag rides at the end of the ciphertext. */
    private const val GCM_TAG_SIZE = 16

    /** One unpacked key file: the cipher [iv] and the encrypted [ciphertext]. */
    data class Payload(val iv: ByteArray, val ciphertext: ByteArray)

    /** Packs one encrypted payload into the on-disk layout. */
    fun pack(iv: ByteArray, ciphertext: ByteArray): ByteArray {
        require(iv.size == IV_SIZE) { "IV must be $IV_SIZE bytes, was ${iv.size}" }
        val out = ByteArray(VERSION_SIZE + IV_SIZE + ciphertext.size)
        out[0] = VERSION.toByte()
        iv.copyInto(out, VERSION_SIZE)
        ciphertext.copyInto(out, VERSION_SIZE + IV_SIZE)
        return out
    }

    /** Unpacks the on-disk layout, or null when the input is truncated or unsupported. */
    fun unpack(bytes: ByteArray): Payload? {
        if (bytes.size < VERSION_SIZE + IV_SIZE + GCM_TAG_SIZE) return null
        if (bytes[0].toInt() != VERSION) return null
        val iv = bytes.copyOfRange(VERSION_SIZE, VERSION_SIZE + IV_SIZE)
        val ciphertext = bytes.copyOfRange(VERSION_SIZE + IV_SIZE, bytes.size)
        return Payload(iv, ciphertext)
    }
}
