#!/usr/bin/env python3
"""Generate app/src/main/res/values/theme_pack_overlays.xml from the pack JSONs.

One theme overlay style per bundled pack (docs/design/themes/packs/<id>.json).
Applying a pack is `theme.applyStyle(R.style.Pack_<Pascal>, true)` — the same
mechanism the accent overlays use, so every `?attr` consumer in the app
follows the pack. Colours are derived the way values/ and values-night/
colors.xml relate to each other:

  inverse/shade/dialogShade colours are the background colour (stock light:
  inkInverse = #FFFFFF = the light background; stock dark: #000000).
  Translucent variants reuse the stock alphas (50%=0x80, 80%=0xCC, 90%=0xE6,
  10%=0x1A, 25%=0x40, 70%=0xB3, 60%=0x99, 6%=0x0F, 7%=0x12, 12%=0x1F, 14%=0x24).
  Text shadows are disabled: pack backgrounds are solid, shadows fight them.

Usage: python3 scripts/generate_theme_pack_styles.py  (run from the repo root)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PACKS_DIR = ROOT / "docs" / "design" / "themes" / "packs"
OUT = ROOT / "app" / "src" / "main" / "res" / "values" / "theme_pack_overlays.xml"

REQUIRED = ["name", "mode", "background", "surface", "ink", "inkMuted",
            "accent", "accentSecondary", "font", "bold"]
OPTIONAL = ["snow"]


def pascal(stem: str) -> str:
    return "".join(part.capitalize() for part in stem.split("-"))


def argb(hex6: str, alpha: str = "FF") -> str:
    return f"#{alpha}{hex6.lstrip('#').upper()}"


def overlay_items(pack: dict) -> list[tuple[str, str]]:
    mode = pack["mode"]
    bg, ink, surface = pack["background"], pack["ink"], pack["surface"]
    accent, muted = pack["accent"], pack["inkMuted"]
    light = mode == "light"
    items = [
        ("android:windowShowWallpaper", "false"),
        ("android:windowBackground", argb(bg)),
        ("android:windowLightStatusBar", "true" if light else "false"),
        ("android:windowLightNavigationBar", "true" if light else "false"),
        ("colorPrimary", argb(ink)),
        ("colorAccent", argb(accent)),
        ("primaryColor", argb(ink)),
        ("primaryInverseColor", argb(bg)),
        ("primaryTextShadowColor", "#00000000"),
        ("primaryColorTrans50", argb(ink, "80")),
        ("primaryColorTrans80", argb(ink, "CC")),
        ("primaryColorInverseTrans50", argb(bg, "80")),
        ("primaryColorInverseTrans80", argb(bg, "CC")),
        ("primaryColorInverseTrans90", argb(bg, "E6")),
        ("primaryShadeColor", argb(bg, "1A")),
        ("primaryShadeDarkColor", argb(bg, "40")),
        ("todayScrimColor", argb(bg, "B3" if light else "99")),
        ("todayPanelColor", argb(ink, "0F") if light else argb(ink, "12")),
        ("todayChipColor", argb(ink, "1F") if light else argb(ink, "24")),
        ("dialogShadeColor", argb(bg, "80")),
        ("accentColor", argb(accent)),
        ("accent", argb(accent)),
        ("ink", argb(ink)),
        ("inkMuted", argb(muted)),
        ("surface", argb(surface)),
    ]
    return items


def main() -> int:
    files = sorted(PACKS_DIR.glob("*.json"))
    if not files:
        print("no pack JSONs found", file=sys.stderr)
        return 1
    packs = {}
    for path in files:
        data = json.loads(path.read_text())
        for field in REQUIRED:
            if field not in data:
                print(f"{path.name}: missing required field {field}", file=sys.stderr)
                return 1
        extra = set(data) - set(REQUIRED) - set(OPTIONAL)
        if extra:
            print(f"{path.name}: unknown fields {sorted(extra)}", file=sys.stderr)
            return 1
        packs[path.stem] = data

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!--",
        "  Generated by scripts/generate_theme_pack_styles.py from",
        "  docs/design/themes/packs/*.json — do not edit by hand.",
        "  One overlay style per bundled pack (#530); applying a pack is",
        "  theme.applyStyle(R.style.Pack_<name>, true) after the font and",
        "  accent overlays, so every ?attr consumer follows the pack.",
        "  Mapping rules are documented in the generator script header.",
        "-->",
        "<resources>",
        "    <!-- Parent holder: the dotted style names below imply this parent style. -->",
        '    <style name="Pack" />',
    ]
    for stem, pack in packs.items():
        lines.append(f'    <!-- {pack["name"]} ({pack["mode"]}, {pack["font"]}, bold={str(pack["bold"]).lower()}) -->')
        lines.append(f'    <style name="Pack.{pascal(stem)}">')
        for name, value in overlay_items(pack):
            lines.append(f'        <item name="{name}">{value}</item>')
        lines.append("    </style>")
        lines.append("")
    lines.append("</resources>")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(packs)} pack overlays")
    return 0


if __name__ == "__main__":
    sys.exit(main())
